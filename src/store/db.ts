import { DatabaseSync, type StatementSync } from "node:sqlite";
import { MIGRATIONS, SCHEMA_MIGRATIONS } from "./schema.js";

/**
 * The database, behind one small interface with two drivers.
 *
 * SQLite is the default: one file on the volume the bot already has, nothing
 * else to run. Postgres is there for a deployment that would rather not keep
 * state on a pod's volume, or already runs a cluster and its backups.
 *
 * The DAOs are written once, in SQL both understand, with `?` placeholders.
 * What differs lives here: how a statement is sent, how a transaction holds
 * its connection, and how the DDL spells a few types (`toDialect`).
 *
 * Everything is async, because Postgres is. With SQLite the calls underneath
 * are synchronous, so a lock keeps a transaction's statements together: while
 * one is open, every other statement waits rather than landing inside it.
 */

export type Dialect = "sqlite" | "postgres";
export type Param = string | number | null;

export interface Db {
  readonly dialect: Dialect;
  all<T>(sql: string, params?: readonly Param[]): Promise<T[]>;
  get<T>(sql: string, params?: readonly Param[]): Promise<T | undefined>;
  /** Runs a statement and reports how many rows it changed. */
  run(sql: string, params?: readonly Param[]): Promise<number>;
  /** One or more statements, no parameters. For DDL. */
  exec(sql: string): Promise<void>;
  /**
   * Everything `fn` does through the handle it is given lands in one
   * transaction. Use that handle, not the outer one: with SQLite the outer
   * one would wait for this transaction to end, forever.
   */
  tx<T>(fn: (tx: Db) => Promise<T>): Promise<T>;
  close(): Promise<void>;
}

/** Rewrites the DDL's SQLite spellings for Postgres. Queries need no rewriting beyond placeholders. */
export function toDialect(sql: string, dialect: Dialect): string {
  if (dialect === "sqlite") return sql;
  return sql
    .replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    // Epoch milliseconds do not fit a 32-bit INTEGER.
    .replace(/\bINTEGER\b/g, "BIGINT")
    .replace(/\bREAL\b/g, "DOUBLE PRECISION")
    .replace(/\)\s*STRICT\s*;/g, ");")
    .replace(/\)\s*STRICT\s*$/g, ")");
}

/** `?` → `$1`, `$2`, … Nothing in this codebase puts a literal `?` in SQL. */
export function numbered(sql: string): string {
  let n = 0;
  return sql.replace(/\?/g, () => `$${(n += 1)}`);
}

// ---- SQLite -----------------------------------------------------------------

class Lock {
  private tail: Promise<unknown> = Promise.resolve();
  run<T>(fn: () => Promise<T>): Promise<T> {
    const next = this.tail.then(fn, fn);
    this.tail = next.catch(() => undefined);
    return next;
  }
}

function sqliteHandle(raw: DatabaseSync, statements: Map<string, StatementSync>): Omit<Db, "tx" | "close"> {
  const prep = (sql: string): StatementSync => {
    let s = statements.get(sql);
    if (!s) {
      s = raw.prepare(sql);
      statements.set(sql, s);
    }
    return s;
  };
  return {
    dialect: "sqlite",
    async all<T>(sql: string, params: readonly Param[] = []) {
      return prep(sql).all(...params) as unknown as T[];
    },
    async get<T>(sql: string, params: readonly Param[] = []) {
      return prep(sql).get(...params) as unknown as T | undefined;
    },
    async run(sql, params = []) {
      return Number(prep(sql).run(...params).changes);
    },
    async exec(sql) {
      raw.exec(sql);
    },
  };
}

/**
 * `node:sqlite` is synchronous underneath. That is an advantage — a commit is
 * a straight-line statement — but it means no unbounded query may sit on the
 * hot path, and the tool-call audit must be batched.
 */
export async function openSqlite(path: string): Promise<Db> {
  const raw = new DatabaseSync(path);
  raw.exec("PRAGMA journal_mode = WAL");
  raw.exec("PRAGMA foreign_keys = ON");
  raw.exec("PRAGMA busy_timeout = 5000");
  // With WAL, the worst case is losing the last few hundred ms of tool-call
  // audit on power loss. Recovery already treats a mid-flight turn as lost.
  raw.exec("PRAGMA synchronous = NORMAL");

  const statements = new Map<string, StatementSync>();
  const inner = sqliteHandle(raw, statements);
  const lock = new Lock();

  const txHandle: Db = {
    ...inner,
    // Already inside the transaction: a nested call simply joins it.
    tx: (fn) => fn(txHandle),
    close: async () => undefined,
  };

  const db: Db = {
    dialect: "sqlite",
    all: (sql, params) => lock.run(() => inner.all(sql, params)),
    get: (sql, params) => lock.run(() => inner.get(sql, params)),
    run: (sql, params) => lock.run(() => inner.run(sql, params)),
    exec: (sql) => lock.run(() => inner.exec(sql)),
    tx: (fn) =>
      lock.run(async () => {
        // BEGIN IMMEDIATE rather than deferred: a deferred transaction that
        // upgrades to a write mid-way can hit SQLITE_BUSY against the WAL
        // checkpointer.
        raw.exec("BEGIN IMMEDIATE");
        try {
          const out = await fn(txHandle);
          raw.exec("COMMIT");
          return out;
        } catch (e) {
          raw.exec("ROLLBACK");
          throw e;
        }
      }),
    close: async () => {
      statements.clear();
      raw.close();
    },
  };
  await migrate(db);
  return db;
}

// ---- Postgres ---------------------------------------------------------------

/** The slice of `pg` this file uses, so the package stays an optional dependency. */
interface PgQueryable {
  query(text: string, values?: unknown[]): Promise<{ rows: unknown[]; rowCount: number | null }>;
}
interface PgClient extends PgQueryable {
  release(): void;
}
interface PgPool extends PgQueryable {
  connect(): Promise<PgClient>;
  end(): Promise<void>;
  on(event: "error", listener: (e: Error) => void): unknown;
}
interface PgModule {
  Pool: new (config: Record<string, unknown>) => PgPool;
  types: { setTypeParser(oid: number, parse: (v: string) => unknown): void };
}

function pgHandle(q: PgQueryable): Omit<Db, "tx" | "close"> {
  return {
    dialect: "postgres",
    async all<T>(sql: string, params: readonly Param[] = []) {
      return (await q.query(numbered(sql), [...params])).rows as T[];
    },
    async get<T>(sql: string, params: readonly Param[] = []) {
      return (await q.query(numbered(sql), [...params])).rows[0] as T | undefined;
    },
    async run(sql, params = []) {
      return (await q.query(numbered(sql), [...params])).rowCount ?? 0;
    },
    async exec(sql) {
      await q.query(sql);
    },
  };
}

export interface PostgresOptions {
  readonly url: string;
  /** A schema of the bot's own, so several bots can share one database. */
  readonly schema?: string | undefined;
  /** Connections in the pool. Five is plenty: one bot, a couple of concurrent turns. */
  readonly poolMax?: number | undefined;
  readonly onError?: (e: Error) => void;
}

const SCHEMA_NAME = /^[a-z_][a-z0-9_]*$/;

export async function openPostgres(opts: PostgresOptions): Promise<Db> {
  let pg: PgModule;
  try {
    const mod = (await import("pg" as string)) as { default?: PgModule } & PgModule;
    pg = mod.default ?? mod;
  } catch {
    throw new Error("DATABASE_URL is set but the `pg` package is not installed — add it to the bot's dependencies");
  }
  // BIGINT and NUMERIC arrive as strings by default. Every number here is an
  // id, a count or epoch milliseconds, all far inside a double's exact range.
  pg.types.setTypeParser(20, (v) => Number(v));
  pg.types.setTypeParser(1700, (v) => Number(v));

  if (opts.schema !== undefined && !SCHEMA_NAME.test(opts.schema)) {
    throw new Error(`DATABASE_SCHEMA: '${opts.schema}' — lowercase letters, digits and underscores only`);
  }

  const pool = new pg.Pool({
    connectionString: opts.url,
    max: opts.poolMax ?? 5,
    ...(opts.schema ? { options: `-c search_path=${opts.schema}` } : {}),
  });
  // An idle client dropping is routine (a failover, a proxy timeout). Without
  // a listener it would take the process down.
  pool.on("error", (e) => opts.onError?.(e));

  if (opts.schema) await pool.query(`CREATE SCHEMA IF NOT EXISTS ${opts.schema}`);

  const db: Db = {
    ...pgHandle(pool),
    async tx(fn) {
      const client = await pool.connect();
      const handle: Db = { ...pgHandle(client), tx: (inner) => inner(handle), close: async () => undefined };
      try {
        await client.query("BEGIN");
        const out = await fn(handle);
        await client.query("COMMIT");
        return out;
      } catch (e) {
        await client.query("ROLLBACK").catch(() => undefined);
        throw e;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
  await migrate(db);
  return db;
}

// ---- Migrations -------------------------------------------------------------

async function migrate(db: Db): Promise<void> {
  await db.exec(toDialect(SCHEMA_MIGRATIONS, db.dialect));
  const applied = new Set((await db.all<{ id: number }>("SELECT id FROM schema_migrations")).map((r) => Number(r.id)));

  for (const m of MIGRATIONS) {
    if (applied.has(m.id)) continue;
    // Each migration and its bookkeeping row land in one transaction, so a
    // crash mid-migration cannot leave a half-applied schema marked as done.
    try {
      await db.tx(async (tx) => {
        if (m.sql) await tx.exec(toDialect(m.sql, tx.dialect));
        if (m.run) await m.run(tx);
        await tx.run("INSERT INTO schema_migrations (id, name, applied_at) VALUES (?, ?, ?)", [m.id, m.name, Date.now()]);
      });
    } catch (e) {
      throw new Error(`migration ${m.id} (${m.name}) failed: ${e instanceof Error ? e.message : String(e)}`);
    }
  }
}
